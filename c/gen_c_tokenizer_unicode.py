#!/usr/bin/env python3
"""Generates c/c_tokenizer_unicode.h: the non-ASCII code points that clang's C23 lexer accepts at the start and in
the rest of an identifier (XID_Start/XID_Continue plus clang's mathematical-notation extension). The sets are measured
by asking clang itself, so they match the clang the tokenizer is checked against.

Usage: python3 c/gen_c_tokenizer_unicode.py [clang]   (run from the repository root; takes about a minute)
"""
import os
import re
import subprocess
import sys
import tempfile

clang = sys.argv[1] if len(sys.argv) > 1 else "clang"
code_points = [cp for cp in range(0x80, 0x110000) if not (0xD800 <= cp <= 0xDFFF)]

with tempfile.TemporaryDirectory() as directory:
    probe = os.path.join(directory, "probe.c")
    # Line i holds "x<cp> <cp>": the first token tells whether <cp> may continue an identifier, the second whether
    # it may start one.
    with open(probe, "wb") as f:
        for cp in code_points:
            utf8 = chr(cp).encode("utf-8")
            f.write(b"x" + utf8 + b" " + utf8 + b"\n")
    process = subprocess.Popen([clang, "-cc1", "-std=c23", "-dump-raw-tokens", probe], stderr=subprocess.PIPE, stdout=subprocess.DEVNULL)
    token = re.compile(rb"^raw_identifier +'(.*)'\s+Loc=<.*probe\.c:(\d+):(\d+)>")
    start, rest = set(), set()
    for line in process.stderr:
        match = token.match(line)
        if not match:
            continue
        cp = code_points[int(match.group(2)) - 1]
        if match.group(3) != b"1":
            start.add(cp)
        elif len(match.group(1)) > 1:
            rest.add(cp)
    process.wait()

assert start <= rest, "every identifier start should also continue an identifier"


def ranges(code_point_set):
    result = []
    for cp in sorted(code_point_set):
        if result and result[-1][1] == cp - 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result


version = subprocess.run([clang, "--version"], capture_output=True, text=True).stdout.splitlines()[0]
with open("c/c_tokenizer_unicode.h", "w") as out:
    out.write("// Generated by c/gen_c_tokenizer_unicode.py from " + version + ".\n")
    out.write("// The non-ASCII code points clang's C23 lexer accepts at the start and in the rest of an identifier, as sorted ranges.\n")
    out.write("#pragma once\n\n#include <stdint.h>\n")
    for name, code_point_set in (("start", start), ("continue", rest)):
        table = ranges(code_point_set)
        out.write(f"\nstatic const uint32_t c_identifier_{name}_ranges[{len(table)}][2] =\n{{\n")
        for i in range(0, len(table), 6):
            out.write("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in table[i:i + 6]) + "\n")
        out.write("};\n")
print(f"{len(start)} start and {len(rest)} continue code points", file=sys.stderr)
