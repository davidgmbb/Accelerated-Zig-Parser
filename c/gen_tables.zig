//! Generates the C port's headers from the Zig implementation, so that both use the same tag values and tables:
//!
//!   zig run --dep CompactingTokenizer -Mroot=c/gen_tables.zig -MCompactingTokenizer=src/CompactingTokenizer.zig -- c
//!
//! writes c/compacting_tokenizer_tags.h (the public tag enum) and c/compacting_tokenizer_tables.h (lookup tables).
//! The table definitions mirror `classifier`, the multi-char symbol channels and `Keywords` in
//! src/CompactingTokenizer.zig; the asserts below check them against its `Tag` values.
const std = @import("std");
const Tag = @import("CompactingTokenizer").Tag;

pub fn main() !void {
    const gpa = std.heap.page_allocator;
    const args = try std.process.argsAlloc(gpa);
    var dir = try std.fs.cwd().openDir(args[1], .{});
    defer dir.close();

    try writeFile(dir, "compacting_tokenizer_tags.h", comptime tagsHeader());
    try writeFile(dir, "compacting_tokenizer_tables.h", comptime tablesHeader());
}

fn writeFile(dir: std.fs.Dir, name: []const u8, contents: []const u8) !void {
    const file = try dir.createFile(name, .{});
    defer file.close();
    try file.writeAll(contents);
}

const generated_notice = "// Generated by c/gen_tables.zig from src/CompactingTokenizer.zig. Do not edit.\n";

/// The C name of a tag: keywords become KEYWORD_<NAME>, symbols are spelled out character by character.
fn cName(comptime name: []const u8) []const u8 {
    comptime {
        if (std.mem.eql(u8, name, "//")) return "COMMENT";
        if (std.mem.eql(u8, name, "///")) return "DOC_COMMENT";
        if (std.mem.eql(u8, name, "//!")) return "CONTAINER_DOC_COMMENT";
        if (std.ascii.isAlphabetic(name[0])) {
            var upper: [name.len]u8 = undefined;
            _ = std.ascii.upperString(&upper, name);
            const is_keyword = for (keywords) |kw| {
                if (std.mem.eql(u8, kw, name)) break true;
            } else false;
            return (if (is_keyword) "KEYWORD_" else "") ++ upper;
        }
        var result: []const u8 = "";
        for (name, 0..) |c, i| {
            if (i != 0) result = result ++ "_";
            result = result ++ switch (c) {
                '!' => "BANG",
                '%' => "PERCENT",
                '&' => "AMPERSAND",
                '(' => "L_PAREN",
                ')' => "R_PAREN",
                '*' => "ASTERISK",
                '+' => "PLUS",
                ',' => "COMMA",
                '-' => "MINUS",
                '.' => "PERIOD",
                '/' => "SLASH",
                ':' => "COLON",
                ';' => "SEMICOLON",
                '<' => "LT",
                '=' => "EQUAL",
                '>' => "GT",
                '?' => "QUESTION_MARK",
                '[' => "L_BRACKET",
                ']' => "R_BRACKET",
                '^' => "CARET",
                '{' => "L_BRACE",
                '|' => "PIPE",
                '}' => "R_BRACE",
                '~' => "TILDE",
                else => @compileError("No C name for character in tag " ++ name),
            };
        }
        return result;
    }
}

fn tagsHeader() []const u8 {
    comptime {
        @setEvalBranchQuota(1_000_000);
        var out: []const u8 = generated_notice ++
            "#pragma once\n\n" ++
            "/// The kind of a token. Same values as `Tag` in src/CompactingTokenizer.zig.\n" ++
            "enum azp_tag {\n";
        for (@typeInfo(Tag).@"enum".fields) |field| {
            if (field.name[0] == '_') continue;
            out = out ++ std.fmt.comptimePrint("    AZP_TAG_{s} = {}, // {s}\n", .{ cName(field.name), field.value, field.name });
        }
        return out ++ "};\n";
    }
}

fn classify(c: u7) Tag {
    return switch (c) {
        0...'\t' - 1, '\n' + 1...'\r' - 1, '\r' + 1...' ' - 1, 0x7F => .invalid,
        '\n', '\r', '\t', ' ' => .whitespace,
        '0'...'9' => .number,
        'a'...'z', 'A'...'Z', '_' => .identifier,
        '\'' => .char_literal,
        '"' => .string,
        '\\' => .double_backslash,
        '@' => .builtin,
        '#', '$', '`' => .unknown,
        else => std.meta.stringToEnum(Tag, &[1]u8{c}).?,
    };
}

const keywords = [_][]const u8{
    "addrspace", "align", "allowzero",   "and",    "anyframe",    "anytype",  "asm",       "break",  "callconv", "catch",
    "comptime",  "const", "continue",    "defer",  "else",        "enum",     "errdefer",  "error",  "export",   "extern",
    "fn",        "for",   "if",          "inline", "noalias",     "noinline", "nosuspend", "opaque", "or",       "orelse",
    "packed",    "pub",   "resume",      "return", "linksection", "struct",   "suspend",   "switch", "test",     "threadlocal",
    "try",       "union", "unreachable", "var",    "volatile",    "while",
};

const superstring =
    "addrspacerrdeferrorelsenumswitchunreachablepackedforeturnunionwhilecontinueconstructcomptimevolatileifnpubreaktestrycatch" ++
    "linksectionosuspendanytypeanyframeandallowzeropaquexporthreadlocallconvaresumexternoinlinealignoaliasm";

fn keywordHash(name: []const u8) u7 {
    const len: u16 = @intCast(name.len);
    const first_two = std.mem.readInt(u16, name[0..2], .little);
    const last_two = std.mem.readInt(u16, name[name.len - 2 ..][0..2], .little);
    return @truncate((((len << 14) ^ first_two) *% last_two) >> 8);
}

fn multiCharSymbolHash(name: []const u8) u8 {
    var word: [4]u8 = @splat(0);
    @memcpy(word[0..name.len], name);
    var hash: u7 = @truncate((std.mem.readInt(u32, &word, .little) *% 698839068) >> 25);
    hash -%= 29;
    return if (hash < 16) @as(u8, hash) + 18 else hash;
}

fn tablesHeader() []const u8 {
    comptime {
        @setEvalBranchQuota(10_000_000);

        var classifier: [128]u8 = undefined;
        for (&classifier, 0..) |*slot, c| slot.* = @intFromEnum(classify(c));

        // The multi-char symbol "channels": bit i of entry `classifier[c]` in table k says that `c` can be
        // character k of a symbol matched by channel i. Bit order follows the `Channels` struct.
        const channels = [_][3][]const u8{
            .{ "-+*", "%|", "=" }, // bar_mod: [-+*][%|]=?
            .{ "|=!%^+*/&<>-", "=", "" }, // eql: [|=!%^+*/&<>-]=
            .{ ".", "*", "*" }, // dot: .**|.*
            .{ "-=", ">", "" }, // arrow: [-=]>
            .{ "<", "<", "|=" }, // <: <<[|=]
            .{ ">", ">", "=" }, // >: >>=
            .{ ".", "?", "" }, // dot_question: .?
            .{ "|.+*", "|.+*", "." }, // self: ([|.+*])(\1)|...
        };
        var char_data: [3][16]u8 = @splat(@splat(0));
        for (channels, 0..) |strings, bit| {
            for (strings, &char_data) |string, *table| {
                for (string) |c| table[classifier[c]] |= 1 << bit;
            }
        }

        var kw_starts: [128]u8 = @splat(0);
        var kw_lens: [128]u8 = @splat(0);
        for (keywords) |kw| {
            const hash = keywordHash(kw);
            if (128 | @as(u8, hash) != @intFromEnum(@field(Tag, kw))) @compileError("Keyword hash doesn't match Tag." ++ kw);
            kw_starts[hash] = std.mem.indexOf(u8, superstring, kw).?;
            kw_lens[hash] = kw.len;
        }

        for (@typeInfo(Tag).@"enum".fields) |field| {
            const name = field.name;
            if (name.len < 2 or std.ascii.isAlphanumeric(name[0]) or name[0] == '_' or name[0] == '/') continue;
            if (multiCharSymbolHash(name) != field.value) @compileError("Multi-char symbol hash doesn't match Tag." ++ name);
        }

        var padded_superstring: [256]u8 = @splat(0);
        @memcpy(padded_superstring[0..superstring.len], superstring);

        return generated_notice ++
            "#pragma once\n#include <stdint.h>\n\n" ++
            byteTable("azp_classifier", &classifier) ++
            byteTable("azp_first_char_data", &char_data[0]) ++
            byteTable("azp_second_char_data", &char_data[1]) ++
            byteTable("azp_third_char_data", &char_data[2]) ++
            byteTable("azp_keyword_starts", &kw_starts) ++
            byteTable("azp_keyword_lens", &kw_lens) ++
            byteTable("azp_keyword_superstring", &padded_superstring) ++
            tagNames();
    }
}

fn byteTable(comptime name: []const u8, comptime bytes: []const u8) []const u8 {
    comptime {
        var out: []const u8 = std.fmt.comptimePrint("static const uint8_t {s}[{}] __attribute__((aligned(64))) = {{", .{ name, bytes.len });
        for (bytes, 0..) |b, i| {
            out = out ++ (if (i % 16 == 0) "\n   " else "") ++ std.fmt.comptimePrint(" {},", .{b});
        }
        return out ++ "\n};\n\n";
    }
}

fn tagNames() []const u8 {
    comptime {
        var out: []const u8 = "static const char *const azp_tag_names[256] = {\n";
        for (@typeInfo(Tag).@"enum".fields) |field| {
            if (field.name[0] == '_') continue;
            out = out ++ std.fmt.comptimePrint("    [{}] = \"{}\",\n", .{ field.value, std.zig.fmtEscapes(field.name) });
        }
        return out ++ "};\n";
    }
}
